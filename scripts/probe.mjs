import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 960, height: 540 } })
page.on('pageerror', e => console.log('pageerror:', e.message))
page.on('console', m => { if (m.type() === 'error' || m.type()==='warning') console.log('console:', m.text().slice(0, 300)) })
const t0 = Date.now()
await page.goto('http://127.0.0.1:3000/')
await page.waitForFunction(() => window.__game?.game?.mode === 'title', null, { timeout: 240000 })
console.log('title after', Date.now() - t0, 'ms', await page.evaluate(() => window.__game.save.data.quality))
const r = await page.evaluate(() => new Promise(res => { let n = 0; const t = performance.now(); const f = () => { n++; if (performance.now() - t < 6000) requestAnimationFrame(f); else res({ n, ms: performance.now() - t }) }; requestAnimationFrame(f) }))
console.log('frames', JSON.stringify(r))
const info = await page.evaluate(() => { const g = window.__game.game; return { calls: g.renderer.gl.info.render.calls, tris: g.renderer.gl.info.render.triangles, px: g.renderer.gl.getPixelRatio() } })
console.log(JSON.stringify(info))
const t1 = Date.now(); await page.screenshot({ path: 'shots/probe.png', timeout: 120000 }); console.log('shot ms', Date.now() - t1)
await browser.close()
